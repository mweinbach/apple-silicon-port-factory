#!/usr/bin/env python3
"""Generate vtables.rs: COM method names in slot order for the D3D12 interfaces
we implement, parsed from third_party/directx-headers/include/directx/*.h
(the C `...Vtbl` structs). Run from the repo root:

    python3 crates/win32-rt/src/d3d12/gen_vtables.py > crates/win32-rt/src/d3d12/vtables.rs
"""
import re

HDR_DIR = 'third_party/directx-headers/include/directx/'
src = ''
for h in ['d3d12.h', 'd3d12sdklayers.h']:
    src += open(HDR_DIR + h, encoding='utf-8', errors='ignore').read()

IFACES = [
    'ID3D12Device14', 'ID3D12CommandQueue1', 'ID3D12CommandAllocator', 'ID3D12GraphicsCommandList10',
    'ID3D12Fence1', 'ID3D12Resource2', 'ID3D12Heap1', 'ID3D12DescriptorHeap', 'ID3D12RootSignature',
    'ID3D12PipelineState1', 'ID3D12QueryHeap', 'ID3D12CommandSignature', 'ID3D12PipelineLibrary1',
    'ID3D12Debug', 'ID3D12Debug1', 'ID3D12Debug3', 'ID3D12Debug6', 'ID3D12DeviceRemovedExtendedDataSettings2',
    'ID3D12InfoQueue1', 'ID3D12RootSignatureDeserializer', 'ID3D12VersionedRootSignatureDeserializer',
    'ID3D12StateObject', 'ID3D12StateObjectProperties1', 'ID3D12DebugDevice2', 'ID3D12DebugCommandList3',
    'ID3D12DebugCommandQueue1', 'ID3D12SDKConfiguration1', 'ID3D12DeviceFactory', 'ID3D12DeviceConfiguration1',
    'ID3D12DeviceRemovedExtendedData2', 'ID3D12ShaderCacheSession', 'ID3D12ProtectedResourceSession1',
]

print('//! COM method names in vtable slot order, generated by `gen_vtables.py` from')
print('//! `third_party/directx-headers` (do not edit by hand).')
print('#![allow(dead_code)]')
print()
for iface in IFACES:
    m = re.search(r'typedef struct %sVtbl\s*\{(.*?)\}\s*%sVtbl;' % (iface, iface), src, re.S)
    if not m:
        raise SystemExit('missing ' + iface)
    body = m.group(1)
    # Methods returning structs have an `#else` branch (C ABI variant with an
    # explicit RetVal pointer); the MSVC branch is the real slot.
    body = re.sub(r'#else.*?#endif', '', body, flags=re.S)
    names = re.findall(r'\(\s*STDMETHODCALLTYPE\s*\*\s*(\w+)\s*\)', body)
    print('pub const %s: &[&str] = &[' % iface)
    for n in names:
        print('    "%s",' % n)
    print('];')
    print()

# IIDs of every interface in the headers: `pub const IID_X: Guid`, plus a
# name table for logging.
iids = re.findall(r'DEFINE_GUID\(IID_(\w+),\s*0x([0-9a-fA-F]+),\s*0x([0-9a-fA-F]+),\s*0x([0-9a-fA-F]+),'
                  r'\s*0x([0-9a-fA-F]+),\s*0x([0-9a-fA-F]+),\s*0x([0-9a-fA-F]+),\s*0x([0-9a-fA-F]+),'
                  r'\s*0x([0-9a-fA-F]+),\s*0x([0-9a-fA-F]+),\s*0x([0-9a-fA-F]+),\s*0x([0-9a-fA-F]+)\);', src)
seen = set()
rows = []
for g in iids:
    if g[0] in seen:
        continue
    seen.add(g[0])
    d4 = ''.join('%02x' % int(x, 16) for x in g[4:])
    s = '%08x-%04x-%04x-%s-%s' % (int(g[1], 16), int(g[2], 16), int(g[3], 16), d4[:4], d4[4:])
    rows.append((g[0], s))
print('use super::com::{guid, Guid};')
print()
for n, s in rows:
    print('pub const IID_%s: Guid = guid("%s");' % (n, s))
print()
print('pub const IID_NAMES: &[(Guid, &str)] = &[')
for n, s in rows:
    print('    (IID_%s, "%s"),' % (n, n))
print('];')
