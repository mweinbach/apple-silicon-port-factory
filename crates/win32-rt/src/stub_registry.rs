const MAX_DETAIL_LEN: usize = 240;

fn truncate_detail(mut s: String) -> String {
    if s.len() > MAX_DETAIL_LEN {
        let mut cut = MAX_DETAIL_LEN;
        while cut > 0 && !s.is_char_boundary(cut) {
            cut -= 1;
        }
        s.truncate(cut);
        s.push_str("...");
    }
    s
}

/// Static descriptor placed at every `stub!`, `failing!`, and `win64_stubs!` site.
pub struct StubSite {
    base_kind: StubKind,
    module_path: &'static str,
    file: &'static str,
    line: u32,
    api: OnceLock<&'static str>,
    first_detail: Mutex<Option<String>>,
    hits: AtomicU64,
    first_frame: AtomicU64,
    first_guest_caller: AtomicU64,
    registered: AtomicBool,
}

impl StubSite {
    pub const fn new(
        base_kind: StubKind,
        module_path: &'static str,
        file: &'static str,
        line: u32,
    ) -> Self {
        Self {
            base_kind,
            module_path,
            file,
            line,
            api: OnceLock::new(),
            first_detail: Mutex::new(None),
            hits: AtomicU64::new(0),
            first_frame: AtomicU64::new(u64::MAX),
            first_guest_caller: AtomicU64::new(0),
            registered: AtomicBool::new(false),
        }
    }

    /// Record one hit at this site and return the previous hit count (`0` on the first hit).
    ///
    /// Fast path (`prev > 0`): single relaxed atomic fetch_add, zero locks, zero allocations.
    #[inline]
    pub fn record_hit(
        &'static self,
        api_name: &'static str,
        get_detail: impl FnOnce() -> String,
    ) -> u64 {
        let prev = self.hits.fetch_add(1, Ordering::Relaxed);
        if prev == 0 {
            self.record_first_hit(api_name, get_detail());
        }
        prev
    }

    #[cold]
    #[inline(never)]
    fn record_first_hit(&'static self, api_name: &'static str, detail: String) {
        let _ = self.api.set(api_name);
        let frame = current_frame();
        let _ = self
            .first_frame
            .compare_exchange(u64::MAX, frame, Ordering::AcqRel, Ordering::Acquire);
        let caller = current_guest_caller_va();
        if caller != 0 {
            let _ = self
                .first_guest_caller
                .compare_exchange(0, caller, Ordering::AcqRel, Ordering::Acquire);
        }
        if let Ok(mut guard) = self.first_detail.lock() {
            if guard.is_none() {
                *guard = Some(truncate_detail(detail));
            }
        }
        if !self.registered.swap(true, Ordering::AcqRel) {
            let mut sites = SITES.lock().unwrap_or_else(|e| e.into_inner());
            sites.push(self);
        }
    }

    fn to_entry(&self) -> Option<StubEntry> {
        let hits = self.hits.load(Ordering::Relaxed);
        if hits == 0 {
            return None;
        }
        let dll = module_path_to_dll(self.module_path);
        let kind = StubKind::classify(self.base_kind, &dll);
        let api = self.api.get().copied().unwrap_or("<unknown>").to_string();
        let raw_frame = self.first_frame.load(Ordering::Acquire);
        let first_frame = if raw_frame == u64::MAX { 0 } else { raw_frame };
        let first_guest_caller_va = self.first_guest_caller.load(Ordering::Acquire);
        let first_guest_caller = if first_guest_caller_va == 0 {
            "<host>".to_string()
        } else {
            crate::symbolize(first_guest_caller_va as usize)
        };
        let first_detail = self
            .first_detail
            .lock()
            .ok()
            .and_then(|g| g.clone())
            .unwrap_or_default();
        Some(StubEntry {
            dll,
            api,
            kind,
            hits,
            first_frame,
            first_guest_caller_va,
            first_guest_caller,
            file: normalize_source_file(self.file),
            line: self.line,
            first_detail,
        })
    }

    fn reset_counts(&self) {
        self.hits.store(0, Ordering::Release);
        self.first_frame.store(u64::MAX, Ordering::Release);
        self.first_guest_caller.store(0, Ordering::Release);
        if let Ok(mut g) = self.first_detail.lock() {
            *g = None;
        }
    }
}

static SITES: Mutex<Vec<&'static StubSite>> = Mutex::new(Vec::new());

