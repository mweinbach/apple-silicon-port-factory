/// One aggregated stub call site in a run snapshot.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct StubEntry {
    pub dll: String,
    pub api: String,
    pub kind: StubKind,
    pub hits: u64,
    pub first_frame: u64,
    pub first_guest_caller_va: u64,
    pub first_guest_caller: String,
    pub file: String,
    pub line: u32,
    pub first_detail: String,
}

/// Complete ranked snapshot of all stubs hit during a run.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct StubSnapshot {
    pub total_hits: u64,
    pub unique_sites: usize,
    pub entries: Vec<StubEntry>,
}

/// Capture a ranked snapshot of every stub hit so far (sorted descending by `hits`).
pub fn snapshot() -> StubSnapshot {
    let sites: Vec<&'static StubSite> = match SITES.try_lock() {
        Ok(v) => v.clone(),
        Err(std::sync::TryLockError::Poisoned(p)) => p.into_inner().clone(),
        Err(std::sync::TryLockError::WouldBlock) => return StubSnapshot::default(),
    };
    let mut entries: Vec<StubEntry> = sites.iter().filter_map(|s| s.to_entry()).collect();
    entries.sort_by(|a, b| {
        b.hits
            .cmp(&a.hits)
            .then_with(|| a.dll.cmp(&b.dll))
            .then_with(|| a.api.cmp(&b.api))
            .then_with(|| a.file.cmp(&b.file))
            .then_with(|| a.line.cmp(&b.line))
    });
    let total_hits = entries.iter().map(|e| e.hits).sum();
    let unique_sites = entries.len();
    StubSnapshot {
        total_hits,
        unique_sites,
        entries,
    }
}

/// Reset all recorded stub hit counts (intended for tests).
pub fn reset_for_test() {
    let sites = SITES.lock().unwrap_or_else(|e| e.into_inner());
    for s in sites.iter() {
        s.reset_counts();
    }
    MANUAL_FRAME.store(u64::MAX, Ordering::Release);
}

/// Override the frame number reported to stub sites (intended for tests; pass `None` to clear).
pub fn set_manual_frame_for_test(frame: Option<u64>) {
    MANUAL_FRAME.store(frame.unwrap_or(u64::MAX), Ordering::Release);
}

impl StubSnapshot {
    /// Format a ranked human-readable summary table for exit logs.
    pub fn format_ranked_table(&self) -> String {
        if self.entries.is_empty() {
            return "=== Stub Registry Summary: 0 stubs hit ===".to_string();
        }
        let mut out = String::new();
        let _ = writeln!(
            out,
            "=== Stub Registry Summary ({} unique sites, {} total hits) ===",
            self.unique_sites, self.total_hits
        );
        let _ = writeln!(
            out,
            "{:>4}  {:>8}  {:>6}  {:<15}  {:<38}  {:<30}  {}",
            "RANK", "HITS", "FRAME", "KIND", "DLL!API", "FIRST_CALLER", "LOCATION"
        );
        for (idx, e) in self.entries.iter().enumerate() {
            let dll_api = format!("{}!{}", e.dll, e.api);
            let loc = format!("{}:{}", e.file, e.line);
            let _ = writeln!(
                out,
                "{:>4}  {:>8}  {:>6}  {:<15}  {:<38}  {:<30}  {}",
                idx + 1,
                e.hits,
                e.first_frame,
                e.kind.as_str(),
                dll_api,
                e.first_guest_caller,
                loc
            );
        }
        out
    }

    /// Serialize this snapshot to RFC 8259 JSON.
    pub fn to_json(&self) -> String {
        let mut out = String::new();
        let _ = writeln!(out, "{{");
        let _ = writeln!(out, "  \"total_hits\": {},", self.total_hits);
        let _ = writeln!(out, "  \"unique_sites\": {},", self.unique_sites);
        let _ = writeln!(out, "  \"entries\": [");
        for (i, e) in self.entries.iter().enumerate() {
            let comma = if i + 1 < self.entries.len() { "," } else { "" };
            let _ = writeln!(
                out,
                "    {{\"dll\":{},\"api\":{},\"kind\":{},\"hits\":{},\"first_frame\":{},\"first_guest_caller_va\":{},\"first_guest_caller\":{},\"file\":{},\"line\":{},\"first_detail\":{}}}{comma}",
                json_quote(&e.dll),
                json_quote(&e.api),
                json_quote(e.kind.as_str()),
                e.hits,
                e.first_frame,
                e.first_guest_caller_va,
                json_quote(&e.first_guest_caller),
                json_quote(&e.file),
                e.line,
                json_quote(&e.first_detail),
            );
        }
        let _ = writeln!(out, "  ]");
        out.push_str("}\n");
        out
    }

    /// Parse a snapshot JSON previously emitted by [`StubSnapshot::to_json`] (or embedded
    /// as a `"stubs"` object inside a boot report).
    pub fn from_json(input: &str) -> Result<Self, String> {
        let mut p = JsonParser::new(input);
        let root = p.parse_value()?;
        Self::from_json_value(&root)
    }

    fn from_json_value(val: &JsonVal) -> Result<Self, String> {
        let obj = val.as_object().ok_or("expected JSON object for StubSnapshot")?;
        let entries_val = obj
            .get("entries")
            .and_then(|v| v.as_array())
            .ok_or("missing 'entries' array in StubSnapshot")?;
        let mut entries = Vec::with_capacity(entries_val.len());
        for item in entries_val {
            let o = item
                .as_object()
                .ok_or("expected JSON object in 'entries'")?;
            let dll = o.get("dll").and_then(|v| v.as_str()).unwrap_or("").to_string();
            let api = o.get("api").and_then(|v| v.as_str()).unwrap_or("").to_string();
            let kind_str = o.get("kind").and_then(|v| v.as_str()).unwrap_or("stub");
            let kind = StubKind::parse(kind_str).unwrap_or(StubKind::Stub);
            let hits = o.get("hits").and_then(|v| v.as_u64()).unwrap_or(0);
            let first_frame = o.get("first_frame").and_then(|v| v.as_u64()).unwrap_or(0);
            let first_guest_caller_va = o
                .get("first_guest_caller_va")
                .and_then(|v| v.as_u64())
                .unwrap_or(0);
            let first_guest_caller = o
                .get("first_guest_caller")
                .and_then(|v| v.as_str())
                .unwrap_or("<host>")
                .to_string();
            let file = o.get("file").and_then(|v| v.as_str()).unwrap_or("").to_string();
            let line = o.get("line").and_then(|v| v.as_u64()).unwrap_or(0) as u32;
            let first_detail = o
                .get("first_detail")
                .and_then(|v| v.as_str())
                .unwrap_or("")
                .to_string();
            entries.push(StubEntry {
                dll,
                api,
                kind,
                hits,
                first_frame,
                first_guest_caller_va,
                first_guest_caller,
                file,
                line,
                first_detail,
            });
        }
        let total_hits = obj
            .get("total_hits")
            .and_then(|v| v.as_u64())
            .unwrap_or_else(|| entries.iter().map(|e| e.hits).sum());
        let unique_sites = obj
            .get("unique_sites")
            .and_then(|v| v.as_u64())
            .map(|n| n as usize)
            .unwrap_or(entries.len());
        Ok(Self {
            total_hits,
            unique_sites,
            entries,
        })
    }
}

/// Difference for a single `(dll, api, kind)` between two runs.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct StubDiffEntry {
    pub dll: String,
    pub api: String,
    pub kind: StubKind,
    pub hits_before: u64,
    pub hits_after: u64,
    pub first_frame_after: Option<u64>,
    pub first_caller_after: Option<String>,
}

impl StubDiffEntry {
    pub fn delta(&self) -> i128 {
        self.hits_after as i128 - self.hits_before as i128
    }
}

/// Diff between two [`StubSnapshot`] runs, aggregated by `(dll, api, kind)`.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct StubDiff {
    pub total_hits_before: u64,
    pub total_hits_after: u64,
    pub unique_apis_before: usize,
    pub unique_apis_after: usize,
    pub added: Vec<StubDiffEntry>,
    pub removed: Vec<StubDiffEntry>,
    pub changed: Vec<StubDiffEntry>,
    pub unchanged_count: usize,
}

impl StubDiff {
    pub fn compute(before: &StubSnapshot, after: &StubSnapshot) -> Self {
        type Key = (String, String, StubKind);
        let aggregate = |snap: &StubSnapshot| -> BTreeMap<Key, (u64, u64, String)> {
            let mut m: BTreeMap<Key, (u64, u64, String)> = BTreeMap::new();
            for e in &snap.entries {
                let key = (e.dll.clone(), e.api.clone(), e.kind);
                m.entry(key)
                    .and_modify(|(h, f, c)| {
                        *h = h.saturating_add(e.hits);
                        if e.first_frame < *f {
                            *f = e.first_frame;
                            *c = e.first_guest_caller.clone();
                        }
                    })
                    .or_insert((e.hits, e.first_frame, e.first_guest_caller.clone()));
            }
            m
        };

        let b_map = aggregate(before);
        let a_map = aggregate(after);

        let mut added = Vec::new();
        let mut removed = Vec::new();
        let mut changed = Vec::new();
        let mut unchanged_count = 0usize;

        for (k, (ah, af, ac)) in &a_map {
            match b_map.get(k) {
                None => added.push(StubDiffEntry {
                    dll: k.0.clone(),
                    api: k.1.clone(),
                    kind: k.2,
                    hits_before: 0,
                    hits_after: *ah,
                    first_frame_after: Some(*af),
                    first_caller_after: Some(ac.clone()),
                }),
                Some((bh, _, _)) if bh != ah => changed.push(StubDiffEntry {
                    dll: k.0.clone(),
                    api: k.1.clone(),
                    kind: k.2,
                    hits_before: *bh,
                    hits_after: *ah,
                    first_frame_after: Some(*af),
                    first_caller_after: Some(ac.clone()),
                }),
                Some(_) => unchanged_count += 1,
            }
        }
        for (k, (bh, _, _)) in &b_map {
            if !a_map.contains_key(k) {
                removed.push(StubDiffEntry {
                    dll: k.0.clone(),
                    api: k.1.clone(),
                    kind: k.2,
                    hits_before: *bh,
                    hits_after: 0,
                    first_frame_after: None,
                    first_caller_after: None,
                });
            }
        }

        added.sort_by(|a, b| b.hits_after.cmp(&a.hits_after).then_with(|| a.dll.cmp(&b.dll)).then_with(|| a.api.cmp(&b.api)));
        removed.sort_by(|a, b| b.hits_before.cmp(&a.hits_before).then_with(|| a.dll.cmp(&b.dll)).then_with(|| a.api.cmp(&b.api)));
        changed.sort_by(|a, b| b.delta().abs().cmp(&a.delta().abs()).then_with(|| a.dll.cmp(&b.dll)).then_with(|| a.api.cmp(&b.api)));

        Self {
            total_hits_before: before.total_hits,
            total_hits_after: after.total_hits,
            unique_apis_before: b_map.len(),
            unique_apis_after: a_map.len(),
            added,
            removed,
            changed,
            unchanged_count,
        }
    }

    pub fn is_empty(&self) -> bool {
        self.added.is_empty() && self.removed.is_empty() && self.changed.is_empty()
    }

    pub fn format_diff(&self) -> String {
        let mut out = String::new();
        let hit_delta = self.total_hits_after as i128 - self.total_hits_before as i128;
        let api_delta = self.unique_apis_after as isize - self.unique_apis_before as isize;
        let _ = writeln!(
            out,
            "=== Stub Registry Diff (APIs: {} -> {} [{:+}], hits: {} -> {} [{:+}]) ===",
            self.unique_apis_before,
            self.unique_apis_after,
            api_delta,
            self.total_hits_before,
            self.total_hits_after,
            hit_delta
        );
        if self.is_empty() {
            let _ = writeln!(out, "  (no changes; {} unchanged APIs)", self.unchanged_count);
            return out;
        }
        if !self.added.is_empty() {
            let _ = writeln!(out, "  NEW stubs hit (+{}):", self.added.len());
            for e in &self.added {
                let _ = writeln!(
                    out,
                    "    + {:>8}  {:<15}  {}!{}  (frame {}, caller {})",
                    e.hits_after,
                    e.kind.as_str(),
                    e.dll,
                    e.api,
                    e.first_frame_after.unwrap_or(0),
                    e.first_caller_after.as_deref().unwrap_or("<host>")
                );
            }
        }
        if !self.removed.is_empty() {
            let _ = writeln!(out, "  RESOLVED stubs (-{}):", self.removed.len());
            for e in &self.removed {
                let _ = writeln!(
                    out,
                    "    - {:>8}  {:<15}  {}!{}",
                    e.hits_before,
                    e.kind.as_str(),
                    e.dll,
                    e.api
                );
            }
        }
        if !self.changed.is_empty() {
            let _ = writeln!(out, "  CHANGED hit counts ({}):", self.changed.len());
            for e in &self.changed {
                let _ = writeln!(
                    out,
                    "    ~ {:>8} -> {:>8} ({:+})  {:<15}  {}!{}",
                    e.hits_before,
                    e.hits_after,
                    e.delta(),
                    e.kind.as_str(),
                    e.dll,
                    e.api
                );
            }
        }
        if self.unchanged_count > 0 {
            let _ = writeln!(out, "  ({} unchanged APIs)", self.unchanged_count);
        }
        out
    }
}

