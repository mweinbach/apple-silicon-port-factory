pub(crate) fn json_quote(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for ch in s.chars() {
        match ch {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if (c as u32) < 0x20 => {
                let _ = write!(out, "\\u{:04x}", c as u32);
            }
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

enum JsonVal {
    Null,
    Bool,
    Num(u64),
    Str(String),
    Arr(Vec<JsonVal>),
    Obj(BTreeMap<String, JsonVal>),
}

impl JsonVal {
    fn as_object(&self) -> Option<&BTreeMap<String, JsonVal>> {
        match self {
            Self::Obj(m) => Some(m),
            _ => None,
        }
    }
    fn as_array(&self) -> Option<&[JsonVal]> {
        match self {
            Self::Arr(v) => Some(v),
            _ => None,
        }
    }
    fn as_str(&self) -> Option<&str> {
        match self {
            Self::Str(s) => Some(s),
            _ => None,
        }
    }
    fn as_u64(&self) -> Option<u64> {
        match self {
            Self::Num(n) => Some(*n),
            _ => None,
        }
    }
}

struct JsonParser<'a> {
    b: &'a [u8],
    i: usize,
}

impl<'a> JsonParser<'a> {
    fn new(s: &'a str) -> Self {
        Self { b: s.as_bytes(), i: 0 }
    }

    fn skip_ws(&mut self) {
        while self.i < self.b.len() && matches!(self.b[self.i], b' ' | b'\n' | b'\r' | b'\t') {
            self.i += 1;
        }
    }

    fn peek(&mut self) -> Option<u8> {
        self.skip_ws();
        self.b.get(self.i).copied()
    }

    fn expect(&mut self, ch: u8) -> Result<(), String> {
        self.skip_ws();
        if self.b.get(self.i) == Some(&ch) {
            self.i += 1;
            Ok(())
        } else {
            Err(format!("expected '{}' at byte {}", ch as char, self.i))
        }
    }

    fn parse_value(&mut self) -> Result<JsonVal, String> {
        match self.peek().ok_or("unexpected EOF")? {
            b'{' => self.parse_object(),
            b'[' => self.parse_array(),
            b'"' => self.parse_string().map(JsonVal::Str),
            b't' => self.parse_lit(b"true", JsonVal::Bool),
            b'f' => self.parse_lit(b"false", JsonVal::Bool),
            b'n' => self.parse_lit(b"null", JsonVal::Null),
            b'-' | b'0'..=b'9' => self.parse_number(),
            c => Err(format!("unexpected byte '{}' at {}", c as char, self.i)),
        }
    }

    fn parse_lit(&mut self, lit: &[u8], val: JsonVal) -> Result<JsonVal, String> {
        if self.b[self.i..].starts_with(lit) {
            self.i += lit.len();
            Ok(val)
        } else {
            Err(format!("invalid literal at byte {}", self.i))
        }
    }

    fn parse_number(&mut self) -> Result<JsonVal, String> {
        let start = self.i;
        if self.b.get(self.i) == Some(&b'-') {
            self.i += 1;
        }
        while self.i < self.b.len()
            && matches!(self.b[self.i], b'0'..=b'9' | b'.' | b'e' | b'E' | b'+' | b'-')
        {
            self.i += 1;
        }
        let s = std::str::from_utf8(&self.b[start..self.i]).map_err(|_| "bad utf8 in number")?;
        if let Ok(u) = s.parse::<u64>() {
            Ok(JsonVal::Num(u))
        } else if let Ok(f) = s.parse::<f64>() {
            Ok(JsonVal::Num(f.max(0.0) as u64))
        } else {
            Err(format!("invalid number {s:?}"))
        }
    }

    fn parse_string(&mut self) -> Result<String, String> {
        self.expect(b'"')?;
        let mut out = String::new();
        while self.i < self.b.len() {
            let c = self.b[self.i];
            self.i += 1;
            if c == b'"' {
                return Ok(out);
            }
            if c == b'\\' {
                let esc = *self.b.get(self.i).ok_or("unterminated escape")?;
                self.i += 1;
                match esc {
                    b'"' => out.push('"'),
                    b'\\' => out.push('\\'),
                    b'/' => out.push('/'),
                    b'b' => out.push('\x08'),
                    b'f' => out.push('\x0c'),
                    b'n' => out.push('\n'),
                    b'r' => out.push('\r'),
                    b't' => out.push('\t'),
                    b'u' => {
                        if self.i + 4 > self.b.len() {
                            return Err("truncated \\u escape".into());
                        }
                        let hex = std::str::from_utf8(&self.b[self.i..self.i + 4])
                            .map_err(|_| "bad \\u hex")?;
                        let code = u32::from_str_radix(hex, 16).map_err(|_| "bad \\u hex")?;
                        self.i += 4;
                        if let Some(ch) = char::from_u32(code) {
                            out.push(ch);
                        }
                    }
                    other => out.push(other as char),
                }
            } else {
                // Handle multi-byte UTF-8 safely
                let start = self.i - 1;
                while self.i < self.b.len() && (self.b[self.i] & 0xC0) == 0x80 {
                    self.i += 1;
                }
                let seg = std::str::from_utf8(&self.b[start..self.i])
                    .map_err(|_| "invalid utf8 in string")?;
                out.push_str(seg);
            }
        }
        Err("unterminated string".into())
    }

    fn parse_array(&mut self) -> Result<JsonVal, String> {
        self.expect(b'[')?;
        let mut v = Vec::new();
        if self.peek() == Some(b']') {
            self.i += 1;
            return Ok(JsonVal::Arr(v));
        }
        loop {
            v.push(self.parse_value()?);
            match self.peek() {
                Some(b',') => {
                    self.i += 1;
                }
                Some(b']') => {
                    self.i += 1;
                    return Ok(JsonVal::Arr(v));
                }
                _ => return Err(format!("expected ',' or ']' at byte {}", self.i)),
            }
        }
    }

    fn parse_object(&mut self) -> Result<JsonVal, String> {
        self.expect(b'{')?;
        let mut m = BTreeMap::new();
        if self.peek() == Some(b'}') {
            self.i += 1;
            return Ok(JsonVal::Obj(m));
        }
        loop {
            let k = self.parse_string()?;
            self.expect(b':')?;
            let v = self.parse_value()?;
            m.insert(k, v);
            match self.peek() {
                Some(b',') => {
                    self.i += 1;
                }
                Some(b'}') => {
                    self.i += 1;
                    return Ok(JsonVal::Obj(m));
                }
                _ => return Err(format!("expected ',' or '}}' at byte {}", self.i)),
            }
        }
    }
}

