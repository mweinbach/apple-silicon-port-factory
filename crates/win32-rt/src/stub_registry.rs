//! Global stub registry: aggregates every runtime `stub!`, `failing!`,
//! `win64_stubs!`, and honest-stub middleware DLL hit across a process run.
//!
//! Each call site holds a `static StubSite` with an atomic hit counter so the
//! hot path (subsequent hits) is a single relaxed atomic increment with zero
//! locks or allocations. On the first hit, the site records:
//! - the current presented frame index (`first_frame`),
//! - the guest caller RIP (`first_guest_caller_va`, symbolized via the loader),
//! - the first formatted detail message, and
//! - registers itself in the process-wide table.
//!
//! At process exit ([`log_exit_summary`], registered by `process::init`), the
//! registry emits a ranked table of every stub hit during the run, optionally
//! writes a JSON snapshot (`PORT_STUB_SUMMARY_JSON`), and optionally prints a
//! diff against a previous run (`PORT_STUB_BASELINE_JSON`).

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::sync::atomic::{AtomicBool, AtomicU64, AtomicUsize, Ordering};
use std::sync::{Mutex, OnceLock};

/// Classification of a registered stub call site.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum StubKind {
    /// Partial/stubbed branch inside a Win32, NT, CRT, D3D, DXGI, or audio API (`stub!`).
    Stub,
    /// Honest failing export stub generated by `failing!` or `win64_stubs!`.
    Failing,
    /// Honest-stub middleware DLL export (`zstd`, `oo2core_9_win64`, `physx_64`,
    /// `physxcooking_64`, `sl.interposer`, etc.).
    MiddlewareStub,
}

impl StubKind {
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Stub => "stub",
            Self::Failing => "failing",
            Self::MiddlewareStub => "middleware_stub",
        }
    }

    pub fn parse(s: &str) -> Option<Self> {
        match s {
            "stub" => Some(Self::Stub),
            "failing" => Some(Self::Failing),
            "middleware_stub" => Some(Self::MiddlewareStub),
            _ => None,
        }
    }

    /// Promote a `Stub` site inside an honest-stub middleware DLL to `MiddlewareStub`,
    /// while preserving `Failing` explicitly.
    pub fn classify(base: Self, dll: &str) -> Self {
        match base {
            Self::Failing => Self::Failing,
            Self::MiddlewareStub => Self::MiddlewareStub,
            Self::Stub => {
                if is_middleware_stub_dll(dll) {
                    Self::MiddlewareStub
                } else {
                    Self::Stub
                }
            }
        }
    }
}

/// Returns `true` for third-party/engine middleware DLLs whose builtin modules are
/// honest fallback stubs or partial compatibility shims.
pub fn is_middleware_stub_dll(dll: &str) -> bool {
    matches!(
        dll,
        "zstd.dll"
            | "oo2core_9_win64.dll"
            | "tbbmalloc.dll"
            | "lz4.dll"
            | "openal32.dll"
            | "libxess.dll"
            | "libxess_dx11.dll"
            | "sl.interposer.dll"
            | "eossdk-win64-shipping.dll"
            | "physx_64.dll"
            | "physxcooking_64.dll"
            | "physx3common_x64.dll"
            | "nvngx_dlss.dll"
            | "amd_fidelityfx_loader_dx12.dll"
            | "amd_ags_x64.dll"
            | "nri.dll"
            | "nrd.dll"
            | "dstorage.dll"
            | "directml.dll"
            | "libcurl.dll"
            | "xaudio2_9redist.dll"
    )
}

/// Map a Rust `module_path!()` inside `win32-rt` to its canonical Windows DLL name.
pub fn module_path_to_dll(module_path: &str) -> String {
    let rest = module_path
        .strip_prefix("win32_rt::")
        .or_else(|| module_path.split_once("::").map(|(_, r)| r))
        .unwrap_or(module_path);
    let mut parts = rest.split("::");
    let first = parts.next().unwrap_or("");
    match first {
        "kernel32" | "sync" | "unwind" | "thread" | "process" | "heap" | "path" | "handles" => {
            "kernel32.dll".to_string()
        }
        "ntdll" | "ntsyscall" => "ntdll.dll".to_string(),
        "ucrt" => "ucrtbase.dll".to_string(),
        "msvcrt" => "msvcrt.dll".to_string(),
        "user32" | "macos" => "user32.dll".to_string(),
        "advapi32" => "advapi32.dll".to_string(),
        "d3d12" => "d3d12.dll".to_string(),
        "dxgi" => "dxgi.dll".to_string(),
        "d3d11" => "d3d11.dll".to_string(),
        "audio" => "mmdevapi.dll".to_string(),
        "slstub" => "sl.interposer.dll".to_string(),
        "eossdk" => "eossdk-win64-shipping.dll".to_string(),
        "misc" => {
            let stem = parts.next().unwrap_or("misc");
            format!("{stem}.dll")
        }
        other if !other.is_empty() => format!("{other}.dll"),
        _ => "win32-rt.dll".to_string(),
    }
}

/// Normalize a compiler `file!()` path to a workspace-relative forward-slash path.
pub fn normalize_source_file(file: &str) -> String {
    let s = file.replace('\\', "/");
    if let Some(idx) = s.find("crates/win32-rt/src/") {
        return s[idx..].to_string();
    }
    s
}

// ---------------------------------------------------------------------------
// Frame & guest caller providers
// ---------------------------------------------------------------------------

pub type FrameProviderFn = fn() -> u64;
pub type GuestCallerFn = fn() -> Option<u64>;

static FRAME_PROVIDER: AtomicUsize = AtomicUsize::new(0);
static GUEST_CALLER_PROVIDER: AtomicUsize = AtomicUsize::new(0);
/// Optional explicit frame override (used when no external provider is set, or in tests).
static MANUAL_FRAME: AtomicU64 = AtomicU64::new(u64::MAX);

/// Register a frame-index provider (e.g. API-neutral present counter across D3D12/D3D11/Vulkan).
pub fn set_frame_provider(f: FrameProviderFn) {
    FRAME_PROVIDER.store(f as usize, Ordering::Release);
}

/// Register a guest-caller-RIP provider (e.g. reading `x86_runtime::emu::current_guest_state`).
pub fn set_guest_caller_provider(f: GuestCallerFn) {
    GUEST_CALLER_PROVIDER.store(f as usize, Ordering::Release);
}

/// Current presented frame number (`0` before the first present).
#[inline]
pub fn current_frame() -> u64 {
    let manual = MANUAL_FRAME.load(Ordering::Acquire);
    if manual != u64::MAX {
        return manual;
    }
    let p = FRAME_PROVIDER.load(Ordering::Acquire);
    if p != 0 {
        let f: FrameProviderFn = unsafe { std::mem::transmute(p) };
        return f();
    }
    crate::dxgi::adapter::global_present_count() as u64
}

/// Current guest caller virtual address, or `0` if invoked from host code / tests.
#[inline]
pub fn current_guest_caller_va() -> u64 {
    let p = GUEST_CALLER_PROVIDER.load(Ordering::Acquire);
    if p != 0 {
        let f: GuestCallerFn = unsafe { std::mem::transmute(p) };
        if let Some(va) = f() {
            return va;
        }
    }
    0
}

